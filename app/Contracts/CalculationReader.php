<?php

declare(strict_types=1);

namespace App\Contracts;

use App\Support\Measurement\StoredCalculation;

/**
 * خواندن یک محاسبه ذخیره‌شده، بدون دانستن اینکه کجا و چطور ذخیره شده.
 *
 * ماژول پروژه‌ها باید بتواند قرائت یک ایستگاه را به محاسبه‌ای که ساخته‌اش وصل
 * کند، ولی حق ندارد مدل ماژول ابزارها را import کند (قاعده ۱). این قرارداد
 * همان مرز است: Tools پیاده‌اش می‌کند، Projects فقط از آن می‌پرسد.
 *
 * اگر ماژول ابزارها غیرفعال باشد، هیچ‌کس این قرارداد را نمی‌بندد و پروژه‌ها
 * با قرائت دستی کار می‌کنند — بدون خطا.
 */
interface CalculationReader
{
    /**
     * محاسبه‌ای که این کاربر مالکش است، یا null.
     *
     * مالکیت عمداً بخشی از پرسش است: بدون آن، هر کاربری می‌توانست با حدس‌زدن
     * شناسه، عدد اندازه‌گیری دیگری را وارد پروژه خودش کند.
     */
    public function findForUser(string $uuid, int $userId): ?StoredCalculation;
}
