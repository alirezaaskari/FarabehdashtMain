<?php

declare(strict_types=1);

namespace App\Contracts;

use App\Support\Tools\ToolSummary;

/**
 * معرفی یک ابزار، بدون دانستن اینکه ابزارها کجا تعریف شده‌اند.
 *
 * دو مصرف‌کننده دارد و هر دو یک چیز می‌خواهند: نام خوانای ابزار به‌جای شناسه
 * لاتین. قالب صنعتی پروژه‌ها فقط عنوان می‌خواهد؛ بلوک ابزار درون متن دانشنامه
 * توضیح و منبع و نسخه را هم نشان می‌دهد.
 *
 * ماژول‌های مصرف‌کننده حق ندارند تعریف ابزار را import کنند (قاعده ۱). این
 * قرارداد همان مرز باریک است و فقط `ToolSummary` از آن عبور می‌کند.
 *
 * اگر ماژول ابزارها غیرفعال باشد، کسی این قرارداد را نمی‌بندد و صفحه‌های
 * مصرف‌کننده بدون بخش ابزار نمایش داده می‌شوند — بدون خطا.
 */
interface ToolDirectory
{
    /** معرفی ابزار، یا null اگر چنین ابزاری وجود نداشته باشد. */
    public function find(string $slug): ?ToolSummary;
}
