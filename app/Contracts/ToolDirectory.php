<?php

declare(strict_types=1);

namespace App\Contracts;

/**
 * نام خوانای یک ابزار، بدون دانستن اینکه ابزارها کجا تعریف شده‌اند.
 *
 * قالب صنعتی هر پروژه فهرستی از «شناسه ابزار» دارد. نمایش خود شناسه لاتین
 * در رابط فارسی خوانا نیست، ولی ماژول پروژه‌ها حق ندارد تعریف ابزار را
 * import کند (قاعده ۱). این قرارداد همان مرز باریک است: فقط یک عنوان.
 *
 * اگر ماژول ابزارها غیرفعال باشد، کسی این قرارداد را نمی‌بندد و صفحه پروژه
 * بدون پیوند ابزار نمایش داده می‌شود — بدون خطا.
 */
interface ToolDirectory
{
    /** عنوان فارسی ابزار، یا null اگر چنین ابزاری وجود نداشته باشد. */
    public function titleFor(string $slug): ?string;
}
