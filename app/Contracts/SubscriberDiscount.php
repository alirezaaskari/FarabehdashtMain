<?php

declare(strict_types=1);

namespace App\Contracts;

use App\Models\User;

/**
 * درصد تخفیف پایداری که اشتراک به یک خریدار می‌دهد.
 *
 * جدا از `EntitlementGate` است چون پرسش جنسش فرق دارد: دروازه «آری یا نه»
 * می‌گوید، این یکی یک عدد. چپاندن عدد داخل پاسخ دروازه یعنی هر مصرف‌کننده‌ای
 * باید بداند کدام فیلد پاسخ برای کدام امکان معنا دارد.
 *
 * پیش‌فرضش `NoDiscount` در `AppServiceProvider` است و ماژول Monetization
 * بازنویسی‌اش می‌کند؛ پس ماژول تجارت هیچ‌وقت شاخه «اگر ماژول درآمدزایی نبود»
 * نمی‌نویسد.
 *
 * تخفیف از سهم پلتفرم کم می‌شود، نه از سهم فروشنده — قاعده‌ای که مصرف‌کننده
 * اجرا می‌کند، نه این قرارداد.
 */
interface SubscriberDiscount
{
    /** صفر یعنی بدون تخفیف. */
    public function percentFor(User $user): float;
}
