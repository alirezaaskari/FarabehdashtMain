<?php

declare(strict_types=1);

namespace App\Support\Payments;

use RuntimeException;

/**
 * درخواست پرداخت به درگاه نرسید یا درگاه آن را نپذیرفت: کلید پذیرنده خالی،
 * قطعی شبکه یا خطای خود درگاه.
 *
 * تقصیر کاربر نیست و پیامش هم برای او نیست (ممکن است نام متغیر محیطی داشته
 * باشد)؛ کنترلر آن را گزارش می‌کند و به کاربر صفحه «پرداخت انجام نشد» با پیامی
 * عمومی نشان می‌دهد، نه خطای ۵۰۰.
 */
final class PaymentGatewayUnavailable extends RuntimeException
{
    /** پیامی که به کاربر نشان داده می‌شود. */
    public const string USER_MESSAGE = 'درگاه پرداخت الان در دسترس نیست. مبلغی کم نشده است؛ چند دقیقه دیگر دوباره تلاش کنید.';
}
