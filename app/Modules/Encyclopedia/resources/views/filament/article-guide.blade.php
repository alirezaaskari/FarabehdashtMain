<div class="flex flex-col gap-3 text-sm leading-7 text-gray-700 dark:text-gray-300">
    <p><strong>ساخت از پنل:</strong> «ساخت» را بزنید، مشخصات را پر کنید، بخش‌ها و منابع را اضافه کنید و ذخیره کنید.
        محتوای تازه پیش‌نویس است و روی سایت نیست.</p>
    <p><strong>نوشته نویسنده‌ها:</strong> کاربری که پروفایل «نویسنده دانشنامه» گرفته (تأیید از «درخواست‌های نقش»)
        از میزکار پیش‌نویس می‌فرستد. نوشته‌های فرستاده‌شده در صف بررسی داشبورد پنل و با وضعیت «در انتظار بازبینی»
        در همین فهرست می‌آیند. متن را هرجا لازم است ویرایش کنید؛ نشانی موقت <code dir="ltr">draft-…</code> را به
        نشانی لاتین خوانا تغییر دهید.</p>
    <p><strong>بازگرداندن:</strong> اگر نوشته آماده نیست، «بازگرداندن به نویسنده» را بزنید و بنویسید چه چیزی
        باید اصلاح شود. نویسنده اعلان می‌گیرد، اصلاح می‌کند و دوباره می‌فرستد.</p>
    <p><strong>انتشار:</strong> پیش از «انتشار» سه چیز لازم است، وگرنه پنل می‌گوید چه چیزی کم است:</p>
    <ul class="list-disc ps-5">
        <li>بازبین علمی و تاریخ بازبینی در بخش «بازبینی علمی»؛</li>
        <li>دست‌کم یک منبع نسخه‌دار (با ویرایش یا سال) برای مقاله، راهنما، واژه‌نامه و مطالعه موردی، و دو منبع برای روش و مقررات؛</li>
        <li>دست‌کم یک بخش.</li>
    </ul>
    <p>پس از انتشار، نشانی ثابت می‌ماند، نویسنده خبردار می‌شود، پیوندهای داخلی بازسازی می‌شوند و هر ذخیره بعدی
        یک نسخه در تاریخچه می‌گذارد. هیچ جمله‌ای نباید ادعای تشخیص پزشکی یا انطباق قانونی قطعی کند.</p>
